/**
 * Generates packages/react/src/library/emoji.generated.ts: the Unicode emoji list (from
 * emojibase-data, MIT) trimmed to what the sticker panel needs — the character, an English name,
 * a category, search words — plus the file name of its 3D sticker art in
 * @lobehub/fluent-emoji-3d (MIT) when there is one. Run when either version changes:
 *   node scripts/gen-emoji.ts
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const FLUENT_VERSION = '1.1.0';
const require = createRequire(import.meta.url);
const data = require('emojibase-data/en/compact.json') as {
  hexcode: string;
  label: string;
  unicode: string;
  group?: number;
  order?: number;
  tags?: string[];
}[];
const pkg = require('emojibase-data/package.json') as { version: string };

const GROUPS: Record<number, string> = {
  0: 'smileys',
  1: 'people',
  3: 'animals',
  4: 'food',
  5: 'travel',
  6: 'activities',
  7: 'objects',
  8: 'symbols',
  9: 'flags',
};

const listing = (await (
  await fetch(
    `https://data.jsdelivr.com/v1/packages/npm/@lobehub/fluent-emoji-3d@${FLUENT_VERSION}?structure=flat`,
  )
).json()) as { files: { name: string }[] };
const files = new Set(
  listing.files
    .map((f) => f.name.match(/^\/assets\/(.+)\.webp$/)?.[1])
    .filter((n): n is string => Boolean(n)),
);

const rows: string[] = [];
let with3d = 0;
for (const e of data
  .filter((d) => d.group !== undefined && d.group !== 2)
  .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))) {
  const hex = e.hexcode.toLowerCase();
  const candidates = [hex, hex.replace(/-fe0f/g, ''), `${hex}-fe0f`];
  const file = candidates.find((c) => files.has(c)) ?? '';
  if (file) with3d++;
  const words = [...new Set([...e.label.toLowerCase().split(/[\s:,]+/), ...(e.tags ?? [])])].join(
    ' ',
  );
  rows.push(JSON.stringify([e.unicode, e.label, GROUPS[e.group!], words, file]));
}

const out = `// Generated by scripts/gen-emoji.ts from emojibase-data@${pkg.version} (MIT) and the file list of
// @lobehub/fluent-emoji-3d@${FLUENT_VERSION} (MIT). Do not edit by hand.

/** [emoji, name, category, search words, 3D art file name or ""]. */
export type EmojiRow = readonly [string, string, string, string, string];

/** Version of the 3D sticker art package the file names refer to. */
export const FLUENT_3D_VERSION = '${FLUENT_VERSION}';

export const EMOJI_ROWS: readonly EmojiRow[] = [
${rows.map((r) => `  ${r},`).join('\n')}
];
`;
writeFileSync('packages/react/src/library/emoji.generated.ts', out);
console.log(`${rows.length} emoji, ${with3d} with 3D art`);
