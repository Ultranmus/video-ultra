/**
 * Generates packages/react/src/library/animated-emoji.generated.ts: which emoji have an animated
 * version in Noto Emoji Animation (Google, CC BY 4.0) and its file code. The sticker panel's
 * Animated tab shows those emoji (as the device draws them) and adds the animated WebP
 * (`<library><code>/512.webp`) as a sticker, with the licence kept on the asset.
 * Usage: node scripts/gen-animated-emoji.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const INDEX = 'https://googlefonts.github.io/noto-emoji-animation/data/api.json';
const out = join(
  import.meta.dirname,
  '..',
  'packages',
  'react',
  'src',
  'library',
  'animated-emoji.generated.ts',
);

interface Icon {
  codepoint: string;
  unsupported_families?: string[];
}

const data = (await (await fetch(INDEX)).json()) as { icons: Icon[] };
const rows: [string, string][] = [];
for (const icon of data.icons) {
  if (icon.unsupported_families?.includes('Noto Animated Emoji')) continue;
  const emoji = String.fromCodePoint(
    ...icon.codepoint.split('_').map((hex) => Number.parseInt(hex, 16)),
  );
  rows.push([emoji.replace(/️/g, ''), icon.codepoint]);
}
rows.sort((a, b) => a[1].localeCompare(b[1]));

writeFileSync(
  out,
  `// Generated by scripts/gen-animated-emoji.ts from the Noto Emoji Animation index
// (${INDEX}; art © Google, CC BY 4.0). Do not edit by hand.

/** Credit line kept on every animated emoji sticker's asset. */
export const ANIMATED_EMOJI_CREDIT = 'Noto Emoji Animation — Google, CC BY 4.0';

/** Emoji (without variation selectors) → its file code in the animation library (${rows.length}). */
export const ANIMATED_EMOJI: ReadonlyMap<string, string> = new Map([
${rows.map(([e, c]) => `  [${JSON.stringify(e)}, ${JSON.stringify(c)}],`).join('\n')}
]);
`,
);
console.log(`${rows.length} animated emoji`);
